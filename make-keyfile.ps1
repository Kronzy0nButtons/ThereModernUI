# ThereModernUI - make-keyfile.ps1
# Makes Resources\compass\klipykey.js from secrets\klipy.key.
# Author: DANKIES
#
# Neither file goes in git. The key is stored XOR'd + base64 so it isn't sat in
# the install as plain text. That won't stop someone who really wants it, if it
# gets abused just revoke it in the KLIPY dashboard and swap in a new one.
#
#   powershell -ExecutionPolicy Bypass -File make-keyfile.ps1 [-Required] [-AlsoTo <client Resources\compass>]

param(
  [switch]$Required,
  [string]$AlsoTo = ''
)
$ErrorActionPreference = 'Stop'
$keyFile = Join-Path $PSScriptRoot 'secrets\klipy.key'
$outFile = Join-Path $PSScriptRoot 'Resources\compass\klipykey.js'

$key = ''
if (Test-Path $keyFile) { $key = (Get-Content $keyFile -Raw).Trim() }
if (-not $key) {
  if ($Required) { throw 'secrets\klipy.key is missing or empty - GIFs need the KLIPY key for a release.' }
  Write-Warning 'secrets\klipy.key not found: building WITHOUT the KLIPY key (GIFs will be unavailable).'
}

# same mask as KLIPY_KEY in dock.js
$mask = [Text.Encoding]::ASCII.GetBytes('ThereModernUI')
$bytes = [Text.Encoding]::ASCII.GetBytes($key)
for ($i = 0; $i -lt $bytes.Length; $i++) { $bytes[$i] = $bytes[$i] -bxor $mask[$i % $mask.Length] }
$blob = [Convert]::ToBase64String($bytes)

$js = @"
// Generated by make-keyfile.ps1 from secrets\klipy.key. Don't edit it, don't commit it.
window.TMUI_KLIPY = '$blob';
"@
Set-Content $outFile $js -Encoding ascii
if ($AlsoTo) { Copy-Item $outFile (Join-Path $AlsoTo 'klipykey.js') -Force }
Write-Host "klipykey.js written ($(if ($key) { 'key present' } else { 'no key' }))."
